#!/usr/bin/env python3
"""Generate src/sites/confusables.ts from Unicode's confusables.txt (PLAN-LOOKALIKE §3).

Usage: python3 -I scripts/gen-confusables.py <path to confusables.txt> > src/sites/confusables.ts

Keeps the entries for one non-ASCII character whose prototype is ASCII letters or digits only
(Cyrillic а → a, fullwidth ｔ → t, ℓ → l); ASCII sources (m → rn) are left to lookalike.ts.
"""
import json
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()
version = re.search(r'^# Version: (\S+)', src, re.M)
date = re.search(r'^# Date: ([^,\n]+)', src, re.M)
table = {}
for line in src.splitlines():
    line = line.split('#', 1)[0].strip()
    if not line:
        continue
    fields = [f.strip() for f in line.split(';')]
    source = [int(c, 16) for c in fields[0].split()]
    target = ''.join(chr(int(c, 16)) for c in fields[1].split()).lower()
    if len(source) != 1 or source[0] < 0x80 or not re.fullmatch(r'[a-z0-9]+', target):
        continue
    table[chr(source[0])] = target

body = json.dumps(dict(sorted(table.items())), ensure_ascii=True, separators=(',', ':'))
print(f'''// Generated by scripts/gen-confusables.py from Unicode confusables.txt, version {version.group(1) if version else '?'} ({date.group(1) if date else '?'}).
// Do not edit by hand. {len(table)} entries: one non-ASCII character → ASCII letters/digits.
export const CONFUSABLES: Readonly<Record<string, string>> = {body};''')
